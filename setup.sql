-- ============================================================================
-- 1. สร้างตาราง items
-- ============================================================================
create table if not exists public.items (
  id bigint generated by default as identity primary key,
  title text not null,
  description text default '',
  price_or_tag text default '',
  image_url text default '',
  created_at timestamptz default now() not null
);

-- เปิดใช้งาน Row Level Security (RLS) บนตาราง items
alter table public.items enable row level security;

-- นโยบายตาราง items: ทุกคนอ่านได้ (Public Read)
create policy "Public can read items"
  on public.items for select
  to anon, authenticated
  using (true);

-- นโยบายตาราง items: เฉพาะผู้ที่ล็อกอินแล้ว (Authenticated) เพิ่ม/แก้ไข/ลบได้
create policy "Authenticated users can insert items"
  on public.items for insert
  to authenticated
  with check (true);

create policy "Authenticated users can update items"
  on public.items for update
  to authenticated
  using (true)
  with check (true);

create policy "Authenticated users can delete items"
  on public.items for delete
  to authenticated
  using (true);

-- ============================================================================
-- 2. สร้าง Storage Bucket ชื่อ images (แบบสาธารณะ - Public Bucket)
-- ============================================================================
insert into storage.buckets (id, name, public)
values ('images', 'images', true)
on conflict (id) do update set public = true;

-- นโยบาย Storage: ทุกคนดูรูปภาพใน bucket 'images' ได้
create policy "Public can view images"
  on storage.objects for select
  to anon, authenticated
  using (bucket_id = 'images');

-- นโยบาย Storage: เฉพาะผู้ที่ล็อกอินแล้ว อัปโหลด/แก้ไข/ลบรูปภาพใน bucket 'images' ได้
create policy "Authenticated users can upload images"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'images');

create policy "Authenticated users can update images"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'images');

create policy "Authenticated users can delete images"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'images');
